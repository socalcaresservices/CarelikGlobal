import { useQuery, useQueryClient } from "@tanstack/react-query";
import { useState } from "react";
import { Button, Card } from "@carelik/ui";
import { formatDuration } from "@/lib/service-verification";
import { hoursLeftText, type HoursFields } from "@/lib/hours-accounting";
import { InfoTip } from "./ui/info-tip";
import { HoursBreakdown } from "@/components/hours-breakdown";
import { useOrganization } from "@/providers/organization-provider";
import { useAwsApi } from "./aws-workspace";
import { clientLabel } from "./name-label";

export interface ChainRow extends HoursFields {
  clientId: string; clientCode: string; clientName?: string | null; duplicateName?: boolean; serviceId: string; serviceCode: string; serviceName: string; authorizationLineageId: string; authorizationVersion: number | null;
  periodStart: string; periodEnd: string; authorizedMinutes: number;
  scheduledMinutes: number; heldReviewMinutes: number; needsReconciliationMinutes: number; reservedMinutes: number;
  workedMinutes: number; confirmedMinutes: number; billableMinutes: number;
  needsCorrectionMinutes: number; waitingMinutes: number; readyForReviewMinutes: number | null; approvedForBillingMinutes: number | null; reviewedNotBillableMinutes: number;
  humanApprovedMinutes: number | null;
  needsCorrectionVisits: number; waitingVisits: number; readyForReviewVisits: number | null; approvedVisits: number | null; voidedApprovals: number | null;
  adjustmentMinutes: number; committedMinutes: number; remainingMinutes: number; overLimitMinutes: number;
  reservedOk: boolean; visitsOk: boolean | null; balanceOk: boolean; differenceMinutes: number;
  /** 0079: Authorized = Billable + Rounding + Pending + Reserved + Hours left. */
  hoursBalanceOk?: boolean;
}

interface ExportRow { exportId: string; requestedAt: string; reportKey: string; params: Record<string, unknown>; requestedByName: string | null; status: "requested" | "generated" | "failed" | "recorded"; generatedAt: string | null; rowCount: number | null; delivery: string }
const STATUS_TEXT: Record<string, string> = {
  requested: "requested, not completed", generated: "generated by the server (delivery not recorded)", failed: "failed, nothing was returned", recorded: "recorded before requests and generation were separated",
};
const REPORT_LABEL: Record<string, string> = {
  client_service_calendar: "Client service calendar", monthly_service_reconciliation: "Monthly hours & billing", correction_history: "Correction history", monthly_chain: "Full chain for the month",
};

/** The export ledger (0069), for the organization owner: who exported what, when, how many rows, and whether the server or the browser made the file. */
function ExportHistory() {
  const api = useAwsApi();
  const { activeOrganizationId, hasPermission } = useOrganization();
  const allowed = hasPermission("organization.update");
  const q = useQuery({
    queryKey: ["report-exports", activeOrganizationId],
    queryFn: async () => (await api.get<{ exports: ExportRow[] }>("/v1/exports", { organizationId: activeOrganizationId })).exports,
    enabled: !!activeOrganizationId && allowed,
  });
  if (!allowed || !q.data || q.data.length === 0) return null;
  return (
    <details className="print:hidden" data-testid="export-history">
      <summary className="inline-flex min-h-6 cursor-pointer items-center [@media(pointer:coarse)]:min-h-[44px] text-sm font-semibold text-slate-800">Export history ({q.data.length})</summary>
      <ul className="mt-1 space-y-1 text-sm text-slate-700">
        {q.data.slice(0, 20).map((e) => (
          <li key={e.exportId}>{new Date(e.requestedAt).toLocaleString()} · {e.requestedByName ?? "Someone"} · {REPORT_LABEL[e.reportKey] ?? e.reportKey} · {e.rowCount === null ? "" : `${e.rowCount} row${e.rowCount === 1 ? "" : "s"} · `} {STATUS_TEXT[e.status] ?? e.status}</li>
        ))}
      </ul>
    </details>
  );
}

const m = (v: number | null | undefined) => (v === null || v === undefined ? "—" : formatDuration(v));
const signed = (v: number) => (v < 0 ? `−${formatDuration(-v)}` : formatDuration(v));

/**
 * The full chain for one month (0070): authorized, scheduled, held, to reconcile, worked, confirmed, billable, by billing state, approved by a person, with checks that the
 * parts add up. The CSV is made by the server and every export is recorded. "Submitted / billed" is deliberately not here: approval is not submission or payment.
 */
export function MonthlyChainReport({ month }: { month: string }) {
  const api = useAwsApi();
  const queryClient = useQueryClient();
  const { activeOrganizationId, hasPermission } = useOrganization();
  const canExport = hasPermission("reports.export");
  const monthStart = `${month}-01`;
  const q = useQuery({
    queryKey: ["monthly-chain", activeOrganizationId, monthStart],
    queryFn: async () => (await api.get<{ rows: ChainRow[] }>("/v1/reports/monthly-chain", { organizationId: activeOrganizationId, monthStart })).rows,
    enabled: !!activeOrganizationId && /^\d{4}-\d{2}$/.test(month),
  });
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [done, setDone] = useState<string | null>(null);
  async function exportCsv() {
    if (busy) return;
    setBusy(true); setError(null); setDone(null);
    try {
      const r = await api.post<{ exportId: string; filename: string; csv: string; rowCount: number }>("/v1/exports", { organizationId: activeOrganizationId, report: "monthly_chain", params: { monthStart } });
      const url = URL.createObjectURL(new Blob([r.csv], { type: "text/csv;charset=utf-8" }));
      const a = document.createElement("a");
      a.href = url; a.download = r.filename; a.click();
      URL.revokeObjectURL(url);
      setDone("The server generated the file and recorded the export. Whether it reached this device is not recorded.");
      await queryClient.invalidateQueries({ queryKey: ["report-exports"] });
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : "The export could not be made. Nothing was downloaded.");
    } finally {
      setBusy(false);
    }
  }
  const rows = q.data ?? [];
  const failing = rows.filter((r) => !r.reservedOk || r.visitsOk === false || !r.balanceOk);
  return (
    <Card className="mt-2 space-y-2 print:border-none print:p-0" data-testid="monthly-chain">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <div className="flex items-center gap-1.5">
          <h3 className="font-semibold text-slate-950">Full chain for the month</h3>
          <InfoTip label="About the full chain">One row per client, service and authorization. Approval is not submission or payment.</InfoTip>
        </div>
        {canExport ? (
          <Button type="button" variant="secondary" className="min-h-11 print:hidden" disabled={busy || rows.length === 0} loading={busy} onClick={() => void exportCsv()}>Export CSV (server-made, recorded)</Button>
        ) : (
          <p className="text-xs text-slate-600 print:hidden">Your role can read this report but not export it.</p>
        )}
      </div>
      <ExportHistory />
      {done ? <p role="status" className="text-sm text-emerald-800">{done}</p> : null}
      {error ? <p role="alert" className="text-sm text-red-700">{error}</p> : null}
      {q.isLoading ? <p className="text-sm text-slate-500">Loading…</p> : null}
      {q.isError ? <p role="alert" className="text-sm text-red-700">{q.error instanceof Error ? q.error.message : "The report could not be loaded."}</p> : null}
      {q.data && rows.length === 0 ? <p className="text-sm text-slate-600" role="status">No authorization overlaps this month.</p> : null}
      {rows.length > 0 ? (
        failing.length === 0
          ? <p role="status" className="text-sm font-semibold text-emerald-800" data-testid="chain-checks">All checks pass: reserved, visits and authorization add up on every row.</p>
          : <p role="alert" className="text-sm font-semibold text-red-700" data-testid="chain-checks">{failing.length} row{failing.length === 1 ? " does" : "s do"} not add up. The difference is shown on each row; do not rely on those totals.</p>
      ) : null}
      {rows.length > 0 ? (
        <div className="overflow-x-auto" tabIndex={0} role="region" aria-label="Full chain by client and service (scrolls sideways on small screens)">
          <table className="w-full min-w-[1100px] border-collapse text-sm">
            <caption className="sr-only">Full chain by client, service and authorization for the selected month</caption>
            <thead>
              <tr className="border-b border-slate-200 text-left text-xs font-semibold text-slate-600">
                <th scope="col" className="py-1 pr-2">Client · service</th>
                <th scope="col" className="px-2 py-1 text-right">Authorized</th>
                <th scope="col" className="px-2 py-1 text-right">Scheduled</th>
                <th scope="col" className="px-2 py-1 text-right">Held (confirming or review)</th>
                <th scope="col" className="px-2 py-1 text-right">To reconcile</th>
                <th scope="col" className="px-2 py-1 text-right">Worked</th>
                <th scope="col" className="px-2 py-1 text-right">Confirmed</th>
                <th scope="col" className="px-2 py-1 text-right">Billable</th>
                <th scope="col" className="px-2 py-1 text-right">Needs correction</th>
                <th scope="col" className="px-2 py-1 text-right">Billing Ready</th>
                <th scope="col" className="px-2 py-1 text-right">Approved</th>
                <th scope="col" className="px-2 py-1 text-right">Rounding</th>
                <th scope="col" className="px-2 py-1 text-right">Pending</th>
                <th scope="col" className="px-2 py-1 text-right">Reserved</th>
                <th scope="col" className="px-2 py-1 text-right">Hours left</th>
                <th scope="col" className="px-2 py-1 text-right">Worked, not billable</th>
                <th scope="col" className="px-2 py-1 text-right">Checks</th>
                <th scope="col" className="py-1 pl-2 text-right">Details</th>
              </tr>
            </thead>
            <tbody className="tabular-nums text-slate-900">
              {rows.map((r) => (
                <tr key={r.authorizationLineageId} className="border-b border-slate-100 last:border-0">
                  <th scope="row" className="py-1 pr-2 text-left font-semibold">{clientLabel(r, true)} · {r.serviceName}</th>
                  <td className="px-2 py-1 text-right">{m(r.authorizedMinutes)}</td>
                  <td className="px-2 py-1 text-right">{m(r.scheduledMinutes)}</td>
                  <td className="px-2 py-1 text-right">{m(r.heldReviewMinutes)}</td>
                  <td className={`px-2 py-1 text-right ${r.needsReconciliationMinutes > 0 ? "font-semibold text-amber-900" : ""}`}>{m(r.needsReconciliationMinutes)}</td>
                  <td className="px-2 py-1 text-right">{m(r.workedMinutes)}</td>
                  <td className="px-2 py-1 text-right">{m(r.confirmedMinutes)}</td>
                  <td className="px-2 py-1 text-right">{m(r.billableMinutes)}</td>
                  <td className="px-2 py-1 text-right">{m(r.needsCorrectionMinutes)}{r.needsCorrectionVisits > 0 ? ` (${r.needsCorrectionVisits})` : ""}</td>
                  <td className="px-2 py-1 text-right">{m(r.readyForReviewMinutes)}</td>
                  <td className="px-2 py-1 text-right">{m(r.humanApprovedMinutes)}</td>
                  <td className="px-2 py-1 text-right">{signed(r.hoursRoundingMinutes ?? r.adjustmentMinutes)}</td>
                  <td className="px-2 py-1 text-right">{m(r.hoursPendingMinutes ?? 0)}</td>
                  <td className="px-2 py-1 text-right">{m(r.hoursReservedMinutes ?? r.reservedMinutes)}</td>
                  <td className={`px-2 py-1 text-right ${(r.hoursLeftMinutes ?? r.remainingMinutes) < 0 ? "font-semibold text-red-700" : ""}`}>{hoursLeftText(r.hoursLeftMinutes ?? r.remainingMinutes)}</td>
                  <td className={`px-2 py-1 text-right ${(r.hoursWorkedNotBillableMinutes ?? 0) > 0 ? "font-semibold text-amber-900" : ""}`}>{m(r.hoursWorkedNotBillableMinutes ?? 0)}</td>
                  <td className="px-2 py-1 text-right">{r.reservedOk && r.visitsOk !== false && r.balanceOk && r.hoursBalanceOk !== false ? <span>Adds up</span> : <span className="font-semibold text-red-700">Off by {formatDuration(Math.abs(r.differenceMinutes))}</span>}</td>
                  <td className="py-1 pl-2 text-right"><HoursBreakdown row={r} /></td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      ) : null}
    </Card>
  );
}
