-- 0069 Report exports need their own permission and leave an audit record (owner request 2026-10-17; matrix row B5-R8).
--
-- BEFORE: any holder of visits.read (owner, manager, scheduler) could download a CSV, built in the browser, with no export permission and no record that it happened.
-- NOW:
--   * permission reports.export, granted to organization_owner and manager. A scheduler can still READ the reports on screen but cannot export them. (A role-policy
--     default chosen by the builder: reversible by granting the permission to another role; confirm it with the owner.)
--   * ogevia_api.record_report_export(org, report, params, row_count, delivery) checks the permission, writes an append-only ledger row (who, when, which report, month and
--     filters, row count, whether it was assembled in the browser or generated by the server) and an audit event, and returns an export id.
--   * ogevia_api.list_report_exports: the ledger, for the organization owner (organization.update).
-- HONEST LIMIT: the three existing CSV buttons (client service calendar, monthly reconciliation, correction history) still assemble the file in the browser from data the
-- person is already allowed to read on screen. They now ask the server to authorize and record the export first, and do nothing if the server refuses; a tampered browser
-- could still copy what is on its own screen. The new full-chain monthly report is generated by the server and recorded in the same transaction. Making the three older
-- exports server-generated is proposed, not done.
-- Rollback (BACKUP REQUIRED: the export ledger is dropped) removes the functions, the permission and its grants.

insert into ogevia.permissions (key, description) values ('reports.export', 'Download or export report data (every export is recorded)');
insert into ogevia.role_permissions (role, permission_key) values ('organization_owner', 'reports.export'), ('manager', 'reports.export');

create table ogevia.report_exports (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references ogevia.organizations(id),
  report_key text not null check (report_key in ('client_service_calendar', 'monthly_service_reconciliation', 'correction_history', 'monthly_chain')),
  params jsonb not null default '{}'::jsonb,
  row_count integer not null check (row_count >= 0 and row_count <= 1000000),
  delivery text not null check (delivery in ('browser_assembled', 'server_generated')),
  exported_by uuid not null references ogevia.app_users(id),
  exported_at timestamptz not null default now()
);
create index report_exports_org on ogevia.report_exports (organization_id, exported_at desc);
create trigger report_exports_no_update before update on ogevia.report_exports for each row execute function ogevia.forbid_update();
create trigger report_exports_no_delete before delete on ogevia.report_exports for each row execute function ogevia.forbid_delete();
alter table ogevia.report_exports enable row level security;
create policy readonly_select on ogevia.report_exports for select to ogevia_readonly using (true);
grant select on ogevia.report_exports to ogevia_readonly;

create function ogevia_api.record_report_export(p_organization_id uuid, p_report_key text, p_params jsonb, p_row_count integer, p_delivery text default 'browser_assembled')
returns jsonb
language plpgsql
volatile
security definer
set search_path = ogevia, pg_temp
as $$
declare
  v_actor uuid := ogevia.require_actor();
  v_id uuid;
  v_at timestamptz;
begin
  if not ogevia.is_active_member(p_organization_id) then raise exception 'Organization not found' using errcode = 'OGN04'; end if;
  if not ogevia.has_permission(p_organization_id, 'reports.export') then raise exception 'You do not have permission to export reports' using errcode = 'OGA03'; end if;
  if not ogevia.has_permission(p_organization_id, 'visits.read') then raise exception 'You do not have permission to export reports' using errcode = 'OGA03'; end if;
  if p_report_key is null or p_report_key not in ('client_service_calendar', 'monthly_service_reconciliation', 'correction_history', 'monthly_chain') then
    raise exception 'Unknown report' using errcode = 'OGV22';
  end if;
  if p_row_count is null or p_row_count < 0 or p_row_count > 1000000 then raise exception 'Invalid row count' using errcode = 'OGV22'; end if;
  if p_delivery is null or p_delivery not in ('browser_assembled', 'server_generated') then raise exception 'Invalid delivery' using errcode = 'OGV22'; end if;
  if p_params is not null and pg_column_size(p_params) > 4000 then raise exception 'Export details are too large' using errcode = 'OGV22'; end if;
  insert into ogevia.report_exports (organization_id, report_key, params, row_count, delivery, exported_by)
  values (p_organization_id, p_report_key, coalesce(p_params, '{}'::jsonb), p_row_count, p_delivery, v_actor) returning id, exported_at into v_id, v_at;
  perform ogevia.write_audit(p_organization_id, 'report.exported', 'report_exports', v_id, null,
    jsonb_build_object('report', p_report_key, 'row_count', p_row_count, 'delivery', p_delivery, 'params', coalesce(p_params, '{}'::jsonb)), null);
  return jsonb_build_object('exportId', v_id, 'exportedAt', v_at);
end;
$$;

create function ogevia_api.list_report_exports(p_organization_id uuid, p_limit integer default 100)
returns table (export_id uuid, exported_at timestamptz, report_key text, params jsonb, row_count integer, delivery text, exported_by_name text)
language plpgsql
stable
security definer
set search_path = ogevia, pg_temp
as $$
begin
  perform ogevia.require_actor();
  if not ogevia.is_active_member(p_organization_id) then raise exception 'Organization not found' using errcode = 'OGN04'; end if;
  if not ogevia.has_permission(p_organization_id, 'organization.update') then raise exception 'You do not have permission to see the export history' using errcode = 'OGA03'; end if;
  return query
  select e.id, e.exported_at, e.report_key, e.params, e.row_count, e.delivery, u.display_name
  from ogevia.report_exports e left join ogevia.app_users u on u.id = e.exported_by
  where e.organization_id = p_organization_id
  order by e.exported_at desc, e.id
  limit greatest(1, least(coalesce(p_limit, 100), 500));
end;
$$;
revoke all on function ogevia_api.record_report_export(uuid, text, jsonb, integer, text) from public;
revoke all on function ogevia_api.list_report_exports(uuid, integer) from public;
grant execute on function ogevia_api.record_report_export(uuid, text, jsonb, integer, text) to ogevia_app;
grant execute on function ogevia_api.list_report_exports(uuid, integer) to ogevia_app;
