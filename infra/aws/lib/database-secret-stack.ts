import { CfnOutput, RemovalPolicy, Stack, Validations, type StackProps } from "aws-cdk-lib";
import * as secretsmanager from "aws-cdk-lib/aws-secretsmanager";
import { Construct } from "constructs";
import { assertDatabaseConfig, type OgeviaEnvironmentConfig } from "./config.js";

export interface DatabaseSecretStackProps extends StackProps {
  readonly config: OgeviaEnvironmentConfig;
}

/**
 * Production application-database credential (env=prd only).
 *
 * Deployed FIRST and alone, so the database step can read the generated
 * password into shell memory and set it on the `ogevia_prd_app` login BEFORE
 * the Lambda that uses it exists. Nothing else in this stack, and the Lambda is
 * not created until the database is provisioned, migrated and verified.
 *
 * - The password is generated by Secrets Manager on creation; it never appears
 *   in source, a template, an output, or a log. CloudFormation does not
 *   regenerate it on later updates.
 * - Distinct from the test slice's `ogevia/database/app`: the login it holds
 *   (ogevia_prd_app) is granted CONNECT on ogevia_prd only.
 * - RETAIN: deleting the stack never deletes the credential.
 */
export class DatabaseSecretStack extends Stack {
  public readonly appSecret: secretsmanager.Secret;

  constructor(scope: Construct, id: string, props: DatabaseSecretStackProps) {
    super(scope, id, { ...props, terminationProtection: props.config.terminationProtection });
    const { config } = props;
    assertDatabaseConfig(config);
    const db = config.database;
    if (db.purpose !== "production" || !db.appLogin || !db.appSecretName) {
      throw new Error("DatabaseSecretStack is only for the production environment");
    }

    this.appSecret = new secretsmanager.Secret(this, "AppDatabaseSecret", {
      secretName: db.appSecretName,
      description: `Ogevia ${config.envName} application database login (${db.name}). Password generated by Secrets Manager.`,
      generateSecretString: {
        secretStringTemplate: JSON.stringify({ username: db.appLogin, dbname: db.name }),
        generateStringKey: "password",
        passwordLength: 40,
        // Safe inside psql variables, URLs and JSON without escaping.
        excludePunctuation: true,
        includeSpace: false,
      },
      removalPolicy: RemovalPolicy.RETAIN,
    });

    new CfnOutput(this, "AppSecretName", { value: this.appSecret.secretName });

    for (const ack of [
      {
        id: "AwsSolutions-SMG4",
        reason:
          "A database password rotation needs a rotation Lambda in the VPC (Secrets Manager endpoint is already shared) and a coordinated login change; it is a post-launch hardening item tracked in docs/aws/PRODUCTION_DEPLOYMENT.md, not part of the initial database path.",
      },
      {
        id: "HIPAA.Security-SecretsManagerRotationEnabled",
        reason: "Same as AwsSolutions-SMG4: rotation is a tracked post-launch item.",
      },
      {
        id: "HIPAA.Security-SecretsManagerUsingKMSKey",
        reason:
          "Encrypted at rest with the AWS managed Secrets Manager key, as the existing application secret is. A customer-managed key is a tracked hardening item.",
      },
    ]) {
      Validations.of(this.appSecret).acknowledge(ack);
    }
  }
}
