import { Tags, type App, type Stack } from "aws-cdk-lib";
import { ProductionAuthStack } from "./auth-stack.js";
import { assertAuthConfig, assertDatabaseConfig, ENVIRONMENTS, forbiddenUserPoolIdsFor, type OgeviaEnvironmentConfig, assertCustomDomains } from "./config.js";
import { DatabaseSecretStack } from "./database-secret-stack.js";
import { EvidenceStorageStack } from "./evidence-storage-stack.js";
import { NetworkEgressStack } from "./network-egress-stack.js";
import { WebHostingStack } from "./web-hosting-stack.js";
import { ObservabilityStack } from "./observability-stack.js";
import { ServiceVerificationApiStack } from "./service-verification-api-stack.js";

/**
 * Synthesis modes.
 * - plan: synth/test/template-diff. Never deploys anything.
 * - deploy: the same stacks, for `cdk deploy` ONLY after the owner's single
 *   consolidated approval (docs/aws/TEST_SLICE_DEPLOYMENT_APPROVAL.md). It
 *   requires OGEVIA_DEPLOY_APPROVAL=<approval reference>, which is written to
 *   every stack's ogevia:deployment-status tag (CLAUDE.md section 13, YELLOW).
 */
export type OgeviaMode = "plan" | "deploy";

const APPROVAL_REF = /^[A-Za-z0-9._-]{6,64}$/;

export function resolveMode(value: unknown, approval?: string): OgeviaMode {
  if (value === "plan") return "plan";
  if (value === "deploy") {
    if (!approval || !APPROVAL_REF.test(approval)) {
      throw new Error(
        "mode=deploy requires OGEVIA_DEPLOY_APPROVAL=<owner approval reference> (6-64 chars [A-Za-z0-9._-]). Use -c mode=plan for synth/test/diff.",
      );
    }
    return "deploy";
  }
  throw new Error(
    `Missing or unknown mode "${String(value)}". Use -c mode=plan (synth/test/diff; never deploy) or -c mode=deploy with an owner approval reference.`,
  );
}

export interface PlannedStack {
  readonly stack: Stack;
  /** CLAUDE.md phase in which the stack may first be deployed. */
  readonly plannedPhase: number;
}

/**
 * Builds every stack for one environment. Shared by bin/ogevia.ts and the
 * tests so the tests assert exactly what `cdk synth` emits.
 *
 * A. EXISTING resources are referenced inside these stacks through
 *    lib/existing-foundation.ts and never appear as template resources.
 * B. Every stack below is NEW FUTURE infrastructure: planned, not deployed.
 */
export function buildOgeviaApp(
  app: App,
  config: OgeviaEnvironmentConfig,
  mode: OgeviaMode = "plan",
  approvalRef?: string,
  options: { readonly alarmEmail?: string | undefined } = {},
): PlannedStack[] {
  assertDatabaseConfig(config);
  assertCustomDomains(config);
  assertAuthConfig(config);
  const env = { account: config.account, region: config.region };
  const production = config.database.purpose === "production";
  const name = (suffix: string) => `Ogevia-${config.envName}-${suffix}`;

  const evidence = new EvidenceStorageStack(app, name("EvidenceStorage"), {
    config,
    env,
    description: `Ogevia ${config.envName} - private encrypted visit signature/evidence storage (FUTURE, Phase 5; not deployed)`,
  });
  // Production shares the pilot's endpoints (private-DNS interface endpoints are
  // unique per VPC); the pilot's NetworkEgress stack admits the production secret,
  // bucket and identity function through its endpoint policies.
  const egress = config.egress.sharedWith
    ? undefined
    : new NetworkEgressStack(app, name("NetworkEgress"), {
        config,
        env,
        description: `Ogevia ${config.envName} - Lambda egress without NAT: Secrets Manager interface + S3 gateway endpoints (D-P1-1; not deployed)`,
      });
  if (config.egress.sharedWith && ENVIRONMENTS[config.egress.sharedWith].egress.sharedWith) {
    throw new Error("egress.sharedWith must name an environment that owns its own endpoints");
  }
  const databaseSecret = (production || config.database.isolatedTest)
    ? new DatabaseSecretStack(app, name("DatabaseSecret"), {
        config,
        env,
        description: `Ogevia ${config.envName} - ${production ? "production" : "isolated TEST"} application database credential (generated by Secrets Manager; no value in the template)`,
      })
    : undefined;
  const web = new WebHostingStack(app, name("WebHosting"), {
    config,
    env,
    description: `Ogevia ${config.envName} - CloudFront + private S3 web hosting and test-slice Cognito app client (Phase 6; not deployed)`,
  });
  // Production's own sign-in (dedicated user pool and client). Created from the web origin only; the web stack itself is unchanged.
  const auth = config.auth.dedicatedUserPool
    ? new ProductionAuthStack(app, name("Auth"), {
        config,
        env,
        webOrigin: web.webOrigin,
        description: `Ogevia ${config.envName} - dedicated Cognito user pool, domain and web app client (separate from the pilot sign-in)`,
      })
    : undefined;
  const api = new ServiceVerificationApiStack(
    app,
    name("ServiceVerificationApi"),
    {
      config,
      env,
      evidenceKey: evidence.dataKey,
      extraAllowedOrigins: [...new Set([web.webOrigin, ...web.customOrigins])],
      ...(auth
        ? {
            authority: {
              userPoolId: auth.userPoolId,
              userPoolArn: auth.userPoolArn,
              appClientIds: [auth.appClientId],
              forbiddenUserPoolIds: forbiddenUserPoolIdsFor(config),
            },
          }
        : { extraAppClientIds: [web.testAppClient.ref] }),
      appDatabaseSecret: databaseSecret?.appSecret,
      description: `Ogevia ${config.envName} - Service Verification API Gateway + Lambda tier (FUTURE, Phase 4; not deployed)`,
    },
  );
  const observability = new ObservabilityStack(app, name("Observability"), {
    config,
    env,
    handler: api.handler,
    api: api.api,
    alarmEmail: options.alarmEmail,
    description: `Ogevia ${config.envName} - operational alarms (FUTURE, Phase 4/7; not deployed)`,
  });

  // The Lambda cannot reach Secrets Manager/S3 until the endpoints exist.
  if (egress) api.addStackDependency(egress, "Lambda egress (D-P1-1) must exist before the API serves traffic");
  if (databaseSecret) api.addDependency(databaseSecret);

  // NOTE: index order is relied on by tests ([evidence, api, observability] first).
  const planned: PlannedStack[] = [
    { stack: evidence, plannedPhase: 5 },
    { stack: api, plannedPhase: 4 },
    { stack: observability, plannedPhase: 4 },
    ...(egress ? [{ stack: egress, plannedPhase: 4 }] : []),
    { stack: web, plannedPhase: 6 },
    ...(databaseSecret ? [{ stack: databaseSecret, plannedPhase: 2 }] : []),
    ...(auth ? [{ stack: auth, plannedPhase: 3 }] : []),
  ];

  Tags.of(app).add("project", "ogevia");
  Tags.of(app).add("environment", config.envName);
  Tags.of(app).add("managed-by", "cdk");
  for (const { stack, plannedPhase } of planned) {
    Tags.of(stack).add("ogevia:ownership", "cdk-future");
    Tags.of(stack).add("ogevia:planned-phase", String(plannedPhase));
    Tags.of(stack).add(
      "ogevia:deployment-status",
      mode === "deploy" && approvalRef ? `approved-${approvalRef}` : "not-approved",
    );
  }
  return planned;
}
