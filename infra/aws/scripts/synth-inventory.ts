// Machine-derived inventory of every synthesized Phase 1 resource.
// Reads cdk.out (run `cdk synth -c env=prod -c mode=plan` first) plus the
// ownership registry and config; makes no AWS calls. Exits 1 if the template
// scanner finds any violation.
//
//   pnpm --filter @carelik/infra-aws inventory -- <output.md>

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ENVIRONMENTS } from "../lib/config.js";
import { ALLOWED_RESOURCE_COST_CLASS } from "../lib/ownership.js";
import { scanTemplate, type CfnTemplate } from "../lib/template-scan.js";

const outFile = process.argv[2];
const cdkOut = new URL("../cdk.out/", import.meta.url).pathname;

type Artifact = {
  type: string;
  properties?: { templateFile?: string; tags?: Record<string, string> };
};
const manifest = JSON.parse(
  readFileSync(join(cdkOut, "manifest.json"), "utf8"),
) as {
  artifacts: Record<string, Artifact>;
};

const rows: string[] = [];
const violations: ReturnType<typeof scanTemplate> = [];
const typeCounts = new Map<string, number>();

for (const [stackName, artifact] of Object.entries(manifest.artifacts)) {
  if (artifact.type !== "aws:cloudformation:stack") continue;
  const template = JSON.parse(
    readFileSync(join(cdkOut, artifact.properties!.templateFile!), "utf8"),
  ) as CfnTemplate;
  const tags = artifact.properties?.tags ?? {};
  const phase = tags["ogevia:planned-phase"] ?? "UNKNOWN";
  const status = tags["ogevia:deployment-status"] ?? "UNKNOWN";
  violations.push(...scanTemplate(stackName, template));
  for (const [logicalId, r] of Object.entries(template.Resources ?? {})) {
    const cost = ALLOWED_RESOURCE_COST_CLASS[r.Type] ?? "UNCLASSIFIED";
    rows.push(
      `| ${stackName} | ${r.Type} | ${logicalId} | NEW (FUTURE, ${status}) | ${phase} | ${cost} |`,
    );
    typeCounts.set(r.Type, (typeCounts.get(r.Type) ?? 0) + 1);
  }
}

// Existing resources referenced by CDK. They never appear in a template.
const e = ENVIRONMENTS.prod.existing;
const refs: Array<[string, string, string]> = [
  ["AWS::EC2::VPC", e.vpc.vpcId, "manual (outside CloudFormation)"],
  ...[...e.vpc.publicSubnets, ...e.vpc.privateSubnets].map(
    (s) =>
      ["AWS::EC2::Subnet", s.subnetId, "manual (outside CloudFormation)"] as [
        string,
        string,
        string,
      ],
  ),
  [
    "AWS::EC2::SecurityGroup",
    e.securityGroups.prodApp,
    `CloudFormation ${e.dataLayerStackName}`,
  ],
  [
    "AWS::EC2::SecurityGroup",
    e.securityGroups.prodRds,
    `CloudFormation ${e.dataLayerStackName}`,
  ],
  [
    "AWS::EC2::SecurityGroup",
    e.securityGroups.dbAdmin,
    "manual (outside CloudFormation)",
  ],
  [
    "AWS::EC2::VPCEndpoint",
    e.ssmEndpoints.ssm,
    "manual (outside CloudFormation)",
  ],
  [
    "AWS::EC2::VPCEndpoint",
    e.ssmEndpoints.ssmMessages,
    "manual (outside CloudFormation)",
  ],
  [
    "AWS::RDS::DBInstance",
    e.databases.prod.instanceIdentifier,
    `CloudFormation ${e.dataLayerStackName}`,
  ],
  [
    "AWS::SecretsManager::Secret",
    "RDS-managed master secret (metadata only)",
    "RDS-managed",
  ],
  [
    "AWS::SecretsManager::Secret",
    "application DB secret (metadata only)",
    "manual (outside CloudFormation)",
  ],
  [
    "AWS::Cognito::UserPool",
    e.cognitoUserPoolId,
    "manual (outside CloudFormation)",
  ],
];
const refRows = refs.map(
  ([type, id, owner]) =>
    `| (none: referenced) | ${type} | ${id} | REFERENCE (existing; owner: ${owner}) | n/a | not billed by CDK |`,
);

const md = [
  "<!-- GENERATED by infra/aws/scripts/synth-inventory.ts from cdk.out. Do not edit by hand. -->",
  "# Phase 1 — Synthesized Resource Inventory",
  "",
  `Generated: ${new Date().toISOString()} · environment: prod · mode: plan`,
  "",
  `Scanner violations: **${violations.length}**`,
  "",
  ...violations.map(
    (v) => `- ${v.stack} / ${v.logicalId}: ${v.rule} (${v.detail})`,
  ),
  "",
  "## Resource counts by type (NEW, synthesized)",
  "",
  "| RESOURCE TYPE | COUNT | COST CLASS |",
  "|---|---|---|",
  ...[...typeCounts.entries()]
    .sort()
    .map(
      ([t, n]) =>
        `| ${t} | ${n} | ${ALLOWED_RESOURCE_COST_CLASS[t] ?? "UNCLASSIFIED"} |`,
    ),
  "",
  "## Full inventory",
  "",
  "| STACK | RESOURCE TYPE | LOGICAL ID | REFERENCE/NEW | PLANNED PHASE | COST CLASS |",
  "|---|---|---|---|---|---|",
  ...rows,
  ...refRows,
  "",
].join("\n");

if (outFile) writeFileSync(outFile, md);
else process.stdout.write(md);
if (violations.length > 0) {
  console.error(`${violations.length} scanner violation(s)`);
  process.exit(1);
}
